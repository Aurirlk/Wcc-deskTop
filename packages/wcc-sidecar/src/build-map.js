/**
 * Bundle WCC campaign sources into a single war3map.lua + dist folder.
 * require() graph is inlined so the map only needs one imported script.
 */
import fs from "node:fs";
import path from "node:path";

const REQUIRE_RE = /\brequire\s*\(\s*(["'])([^"']+)\1\s*\)/g;

function toFilePath(root, moduleName) {
  // src.lib.wcc-core / src/lib/wcc-core / src/main
  const rel = moduleName.replace(/\./g, "/") + ".lua";
  const candidates = [
    path.join(root, rel),
    path.join(root, moduleName + ".lua"),
    path.join(root, "src", rel),
    path.join(root, "wcc-lib", path.basename(rel)),
    path.join(root, "src", "lib", path.basename(rel)),
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return null;
}

function collectModules(root, entryModule, wccLibDir) {
  const resolved = new Map(); // moduleName -> { file, code, deps: string[] }
  const queue = [entryModule];
  const seen = new Set();

  while (queue.length) {
    const mod = queue.shift();
    if (seen.has(mod)) continue;
    seen.add(mod);

    let file = toFilePath(root, mod);
    if (!file && wccLibDir) {
      const base = path.basename(mod.replace(/\./g, "/")) + ".lua";
      const alt = path.join(wccLibDir, base);
      if (fs.existsSync(alt)) file = alt;
    }
    if (!file) {
      resolved.set(mod, { file: null, code: null, deps: [], missing: true });
      continue;
    }
    let code = fs.readFileSync(file, "utf8");
    // strip shebang
    code = code.replace(/^#![^\n]*\n/, "");
    const deps = [];
    let m;
    const re = new RegExp(REQUIRE_RE.source, "g");
    while ((m = re.exec(code))) {
      deps.push(m[2]);
    }
    resolved.set(mod, { file, code, deps });
    for (const d of deps) queue.push(d);
  }
  return resolved;
}

function rewriteRequires(code, mapName) {
  return code.replace(REQUIRE_RE, (full, q, mod) => {
    if (mapName.has(mod)) return `__wcc_require(${JSON.stringify(mod)})`;
    return full;
  });
}

export function bundleCampaign({ projectRoot, entry = "src.main", outDir }) {
  const dist = outDir || path.join(projectRoot, "dist", "build");

  const wccLibDir = [
    path.join(projectRoot, "wcc-lib"),
    path.join(projectRoot, "..", "wcc-lib"),
    path.join(projectRoot, "..", "..", "wcc-lib"),
  ].find((d) => fs.existsSync(d));

  const mods = collectModules(projectRoot, entry, wccLibDir);
  const missing = [...mods.entries()].filter(([, v]) => v.missing).map(([k]) => k);

  // Fail fast: a bundle with unresolved requires would boot into
  // `__wcc_require(...): module not found` at runtime. Never emit a partial
  // war3map.lua and report success (see docs/NEXT-DEVELOPMENT-PLAN.md N1).
  if (missing.length) {
    throw new Error(
      `[WCC build] unresolved modules, no artifact written: ${missing.join(", ")}. ` +
      `entry=${entry} projectRoot=${projectRoot}. ` +
      `Add the missing .lua files or fix the require() graph before building.`
    );
  }

  fs.mkdirSync(dist, { recursive: true });

  // Topological-ish: emit deps first via simple multiple passes
  const emitted = new Set();
  const parts = [];
  parts.push(`--[[
  Generated by WCC build_map
  entry: ${entry}
  date: ${new Date().toISOString()}
]]
local __wcc_modules = {}
local __wcc_cache = {}
function __wcc_require(name)
  if __wcc_cache[name] then return __wcc_cache[name] end
  local loader = __wcc_modules[name]
  if not loader then
    error("[WCC] module not found in bundle: " .. tostring(name), 2)
  end
  local mod = loader()
  __wcc_cache[name] = mod ~= nil and mod or true
  return __wcc_cache[name]
end
`);

  function emit(modName) {
    if (emitted.has(modName) || !mods.has(modName)) return;
    const rec = mods.get(modName);
    if (rec.missing) return;
    for (const d of rec.deps) {
      if (mods.has(d) && !mods.get(d).missing) emit(d);
    }
    if (emitted.has(modName)) return;
    const body = rewriteRequires(rec.code, new Set([...mods.keys()].filter((k) => !mods.get(k).missing)));
    parts.push(`__wcc_modules[${JSON.stringify(modName)}] = function()
${body}
end
`);
    emitted.add(modName);
  }

  for (const name of mods.keys()) emit(name);

  parts.push(`
-- boot
local ok, err = pcall(__wcc_require, ${JSON.stringify(entry)})
if not ok then
  print("[WCC] boot failed: " .. tostring(err))
end
`);

  const bundle = parts.join("\n");
  const outFile = path.join(dist, "war3map.lua");
  fs.writeFileSync(outFile, bundle, "utf8");

  // also copy source tree for WE import / debugging
  const srcOut = path.join(dist, "src-tree");
  fs.rmSync(srcOut, { recursive: true, force: true });
  function copyDir(from, to) {
    if (!fs.existsSync(from)) return;
    fs.mkdirSync(to, { recursive: true });
    for (const name of fs.readdirSync(from)) {
      const a = path.join(from, name);
      const b = path.join(to, name);
      const st = fs.statSync(a);
      if (st.isDirectory()) copyDir(a, b);
      else if (name.endsWith(".lua")) fs.copyFileSync(a, b);
    }
  }
  copyDir(path.join(projectRoot, "src"), path.join(srcOut, "src"));
  if (wccLibDir) copyDir(wccLibDir, path.join(srcOut, "wcc-lib"));

  const readme = `# WCC 构建产物

- \`war3map.lua\`：单文件打包（内联 __wcc_require，**不依赖游戏原生 require**）
- \`src-tree/\`：源码副本

## 如何进图（重要）

**WC3 原生 Lua 没有 require。** 必须：

1. **推荐**：地图脚本直接使用本目录 \`war3map.lua\`，不要在 WE 里写 \`require("src.main")\`。
2. 仅当使用 YDWE/w3x2lni 等支持多文件导入的工具链时，才用目录结构 + 其自带 require。

WE：打开地图 → 脚本编辑器 → 替换为 \`war3map.lua\` 全文。

⚠️ \`src-tree/\` 里的 \`wcc-lib/wcc-hotreload.lua\` 依赖原生 require，
WC3 目标环境不可用，**不要导入 WE**；详见仓库 \`docs/P0-DISPOSITIONS.md\` N6。

完整 MPQ 写入需要 mpyq/stormlib/WE；本构建产出可导入脚本包，**不产出 \`.w3x\`**。
`;
  fs.writeFileSync(path.join(dist, "README.md"), readme, "utf8");

  const stats = {
    entry,
    modules: [...emitted],
    missing,
    war3map: outFile,
    bytes: bundle.length,
    dist,
  };
  fs.writeFileSync(path.join(dist, "build-stats.json"), JSON.stringify(stats, null, 2), "utf8");
  return stats;
}
